
SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
    SUM(QUANTITY) AS TOTAL_UNITS,
    SUM(GROSS_SALES) AS TOTAL_SALES,
    AVG(GROSS_SALES) AS AVG_ORDER_VALUE
FROM {{ ref('fct_sales') }}
GROUP BY
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY
